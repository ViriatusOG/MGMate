// CI passes the release's version; a local build is a development one.
val appVersionName = (findProperty("mgmate.versionName") as String?) ?: "0.0.0-dev"
val appVersionCode = ((findProperty("mgmate.versionCode") as String?) ?: "1").toInt()

// The signing key never lives in the repository. CI hands it over through these variables; without
// them the release build is signed with the debug key of the machine that builds it.
val keystorePath: String? = System.getenv("MGMATE_KEYSTORE_FILE")

android {
    namespace = "io.github.viriatusog.mgmate"
    compileSdk = 35

    defaultConfig {
        applicationId = "io.github.viriatusog.mgmate"
        minSdk = 26
        targetSdk = 35
        versionCode = appVersionCode
        versionName = appVersionName
    }

    signingConfigs {
        if (keystorePath != null) {
            create("release") {
                storeFile = file(keystorePath)
                storePassword = System.getenv("MGMATE_KEYSTORE_PASSWORD")
                keyAlias = System.getenv("MGMATE_KEY_ALIAS")
                keyPassword = System.getenv("MGMATE_KEY_PASSWORD")
            }
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            signingConfig = signingConfigs.findByName("release") ?: signingConfigs.getByName("debug")
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

